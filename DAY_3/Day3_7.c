// Arithmatic Operators: + -  * / %
// Binary operator

#include<stdio.h>
int main(){
    int num1=20;
    int num2=10;
    int res=num1-num2;
    printf("res is %d\n",res);
    printf("%d + %d is %d\n",num1,num2,num1+num2);
    printf("%d - %d is %d\n",num1,num2,num1-num2);
    printf("%d %% %d is %d\n",num1,num2,num1%num2);
    printf("%d / %d is %d\n",num1,num2,num1/num2);
}
